get_ubuntu_codename() {
    local codename=""
    if [[ -r /etc/os-release ]]; then
        codename=$(awk -F= '$1 == "VERSION_CODENAME" {print $2}' /etc/os-release 2>/dev/null | tr -d '"'\''')
        [[ -z "$codename" ]] && codename=$(awk -F= '$1 == "UBUNTU_CODENAME" {print $2}' /etc/os-release 2>/dev/null | tr -d '"'\''')
    fi
    if [[ -z "$codename" ]] && command -v lsb_release >/dev/null 2>&1; then
        codename=$(lsb_release -cs 2>/dev/null || true)
    fi
    echo "${codename,,}"
}

is_known_eol_ubuntu_codename() {
    local codename="$1"
    case "$codename" in
        artful|bionic|cosmic|disco|eoan|groovy|hirsute|impish|kinetic|lunar|mantic|trusty|utopic|vivid|wily|xenial|yakkety|zesty)
            return 0
            ;;
        *)
            return 1
            ;;
    esac
}

rewrite_ubuntu_apt_sources() {
    local target_file="$1" codename="$2" mirror_host="$3"
    local has_security_pocket=1
    [[ "$mirror_host" == "old-releases.ubuntu.com" ]] && has_security_pocket=0

    {
        echo "# Auto-generated by ProgoCloud APT compatibility manager"
        echo "deb http://${mirror_host}/ubuntu/ ${codename} main restricted universe multiverse"
        echo "deb http://${mirror_host}/ubuntu/ ${codename}-updates main restricted universe multiverse"
        echo "deb http://${mirror_host}/ubuntu/ ${codename}-backports main restricted universe multiverse"
        if (( has_security_pocket == 1 )); then
            echo "deb http://${mirror_host}/ubuntu/ ${codename}-security main restricted universe multiverse"
        else
            echo "deb http://${mirror_host}/ubuntu/ ${codename}-security main restricted universe multiverse"
        fi
    } > "$target_file"
}

repair_ubuntu_apt_mirrors() {
    local codename
    codename=$(get_ubuntu_codename)
    [[ -z "$codename" ]] && return 1
    if is_known_eol_ubuntu_codename "$codename"; then
        switch_ubuntu_to_old_releases "$codename"
        return $?
    fi
    return 1
}

switch_ubuntu_to_old_releases() {
    local codename="$1"
    [[ -z "$codename" ]] && codename=$(get_ubuntu_codename)
    [[ -z "$codename" ]] && return 1
    if [[ -f /etc/apt/sources.list && ! -f /etc/apt/sources.list.pgy-backup ]]; then
        cp /etc/apt/sources.list /etc/apt/sources.list.pgy-backup 2>/dev/null || true
    fi
    rewrite_ubuntu_apt_sources /etc/apt/sources.list "$codename" "old-releases.ubuntu.com"
}

repair_debian_apt_mirrors() {
    local codename=""
    if [[ -r /etc/os-release ]]; then
        codename=$(awk -F= '$1 == "VERSION_CODENAME" {print $2}' /etc/os-release 2>/dev/null | tr -d '"'\''')
    fi
    [[ -z "$codename" ]] && return 1
    if [[ -f /etc/apt/sources.list && ! -f /etc/apt/sources.list.pgy-backup ]]; then
        cp /etc/apt/sources.list /etc/apt/sources.list.pgy-backup 2>/dev/null || true
    fi
    {
        echo "# Auto-generated by ProgoCloud APT compatibility manager"
        echo "deb http://deb.debian.org/debian ${codename} main contrib non-free"
        echo "deb http://deb.debian.org/debian ${codename}-updates main contrib non-free"
        echo "deb http://security.debian.org/debian-security ${codename}-security main contrib non-free"
    } > /etc/apt/sources.list
}

pgy_apt_update() {
    local apt_out
    export DEBIAN_FRONTEND=noninteractive
    if apt_out=$(apt-get update 2>&1); then
        return 0
    fi
    if [[ "$apt_out" =~ 404.*Not\ Found|archive\.ubuntu\.com|security\.ubuntu\.com ]]; then
        repair_ubuntu_apt_mirrors 2>/dev/null || repair_debian_apt_mirrors 2>/dev/null || true
        apt-get update -y 2>&1 || true
    fi
    return 0
}
tdz_apt_update() { pgy_apt_update "$@"; }

pgy_apt_install() {
