harden_sshd_for_tunnel_stability() {
    local target="/etc/ssh/sshd_config.d/pgytunnel.conf"
    mkdir -p /etc/ssh/sshd_config.d
    cat <<'EOF' > "$target"
# Auto Script SSH By : ProgoCloud
# SSH Tunneling Optimization
ClientAliveInterval 30
ClientAliveCountMax 3
MaxSessions 100
MaxStartups 100:30:200
TCPKeepAlive yes
X11Forwarding yes
PermitTunnel yes
AllowTcpForwarding yes
GatewayPorts yes
Banner /etc/pgytunnel/bannerssh
EOF
    chmod 644 "$target" 2>/dev/null || true
}

_is_valid_ipv4() {
    local ip="$1"
    local rx='^([0-9]{1,3}\.){3}[0-9]{1,3}$'
    [[ "$ip" =~ $rx ]] || return 1
    local IFS='.'
    read -r -a octets <<< "$ip"
    for oct in "${octets[@]}"; do
        (( oct >= 0 && oct <= 255 )) || return 1
    done
    return 0
}

pgy_record_firewall_rule() {
    local tool="$1" proto="$2" port="$3"
    mkdir -p "$DB_DIR"
    echo "${tool}|${proto}|${port}" >> "$FIREWALL_STATE_FILE"
}
tdz_record_firewall_rule() { pgy_record_firewall_rule "$@"; }

pgy_remove_recorded_firewall_rules() {
    [[ -f "$FIREWALL_STATE_FILE" ]] || return 0
    while IFS='|' read -r tool proto port; do
        [[ -n "$tool" && -n "$proto" && -n "$port" ]] || continue
        case "$tool" in
            ufw)
                ufw delete allow "${port}/${proto}" >/dev/null 2>&1 || true
                ;;
            iptables)
                iptables -D INPUT -p "$proto" --dport "$port" -j ACCEPT 2>/dev/null || true
                ip6tables -D INPUT -p "$proto" --dport "$port" -j ACCEPT 2>/dev/null || true
                ;;
        esac
    done < "$FIREWALL_STATE_FILE"
    rm -f "$FIREWALL_STATE_FILE"
}
tdz_remove_recorded_firewall_rules() { pgy_remove_recorded_firewall_rules "$@"; }

check_and_open_firewall_port() {
    local port="$1" proto="${2:-tcp}"
    if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q "Status: active"; then
        ufw allow "${port}/${proto}" >/dev/null 2>&1 || true
        pgy_record_firewall_rule "ufw" "$proto" "$port"
    elif command -v iptables >/dev/null 2>&1; then
        iptables -C INPUT -p "$proto" --dport "$port" -j ACCEPT >/dev/null 2>&1 || {
            iptables -I INPUT -p "$proto" --dport "$port" -j ACCEPT >/dev/null 2>&1 || true
            pgy_record_firewall_rule "iptables" "$proto" "$port"
        }
    fi
}

check_and_open_firewall_port_range() {
    local start="$1" end="$2" proto="${3:-udp}"
    if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q "Status: active"; then
        ufw allow "${start}:${end}/${proto}" >/dev/null 2>&1 || true
    elif command -v iptables >/dev/null 2>&1; then
        iptables -C INPUT -p "$proto" --dport "${start}:${end}" -j ACCEPT >/dev/null 2>&1 || {
            iptables -I INPUT -p "$proto" --dport "${start}:${end}" -j ACCEPT >/dev/null 2>&1 || true
        }
    fi
}
